#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'brand/svg');
const WORDMARK_SOURCE = resolve(ROOT, 'brand/source/proso-wordmark-construction.svg');

const NAVY = '#010616';
const INK = '#F8F8F9';
const GREEN = '#21F299';

function escapeXml(value) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function document({ viewBox, title, description, body }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-labelledby="title desc">
  <!-- Generated by scripts/generate-brand-vectors.mjs; do not edit. -->
  <title id="title">${escapeXml(title)}</title>
  <desc id="desc">${escapeXml(description)}</desc>
${body}
</svg>
`;
}

function waveMarkBody(bubble, detail, indent = '  ') {
  return `${indent}<g id="bubble" fill="none" stroke="${bubble}" stroke-width="40" stroke-linecap="round" stroke-linejoin="round">
${indent}  <path id="bubble-outline" d="M292 111V92c0-31-25-56-56-56H108c-31 0-56 25-56 56v178l16 18 42-56h126c31 0 56-25 56-56v-8"/>
${indent}</g>
${indent}<g id="text-pills" fill="${detail}">
${indent}  <rect id="text-pill-primary" x="92" y="101" width="152" height="26" rx="13"/>
${indent}  <rect id="text-pill-secondary" x="92" y="148" width="128" height="26" rx="13"/>
${indent}</g>
${indent}<g id="waveform" fill="${detail}">
${indent}  <rect id="waveform-1" x="329" y="115" width="26" height="62" rx="13"/>
${indent}  <rect id="waveform-2" x="371" y="84" width="26" height="124" rx="13"/>
${indent}  <rect id="waveform-3" x="413" y="49" width="26" height="194" rx="13"/>
${indent}  <rect id="waveform-4" x="455" y="95" width="26" height="102" rx="13"/>
${indent}</g>`;
}

function dotMarkBody(color, indent = '  ') {
  return `${indent}<g id="bubble" fill="none" stroke="${color}" stroke-width="40" stroke-linecap="round" stroke-linejoin="round">
${indent}  <path id="bubble-outline" d="M292 92c0-31-25-56-56-56H108c-31 0-56 25-56 56v178l16 18 42-56h138c24 0 44-20 44-44"/>
${indent}</g>
${indent}<circle id="bubble-waist-cap" cx="292" cy="140" r="20" fill="${color}"/>
${indent}<g id="text-pills" fill="${color}">
${indent}  <rect id="text-pill-primary" x="92" y="101" width="116" height="26" rx="13"/>
${indent}  <rect id="text-pill-secondary" x="92" y="148" width="116" height="26" rx="13"/>
${indent}</g>
${indent}<circle id="voice-dot" cx="230" cy="114" r="11" fill="${color}"/>`;
}

function loadWordmarkGroup(fill) {
  const source = readFileSync(WORDMARK_SOURCE, 'utf8');
  const start = source.indexOf('<g id="wordmark"');
  const end = source.lastIndexOf('</g>');
  if (start === -1 || end < start) throw new Error('wordmark source group is missing');
  const group = source.slice(start, end + 4);
  if (!group.includes('fill="#F8F8F9"')) throw new Error('wordmark source fill anchor changed');
  return group.replace('fill="#F8F8F9"', `fill="${fill}"`);
}

function wordmarkDocument(fill, title) {
  const group = loadWordmarkGroup(fill)
    .split('\n')
    .map((line) => `  ${line}`)
    .join('\n');
  return document({
    viewBox: '0 -30 5000 1466',
    title,
    description: 'The lowercase Proso wordmark in custom geometric letterforms.',
    body: group,
  });
}

function lockupDocument({ bubble, detail, wordmark, title }) {
  const mark = waveMarkBody(bubble, detail, '    ');
  const wordmarkGroup = loadWordmarkGroup(wordmark)
    .split('\n')
    .map((line) => `      ${line}`)
    .join('\n');
  return document({
    viewBox: '0 0 1210 320',
    title,
    description: 'The Proso text-to-voice symbol followed by the lowercase Proso wordmark.',
    body: `  <g id="mark">
${mark}
  </g>
  <g id="lockup-wordmark" transform="translate(597 94) scale(.116)">
${wordmarkGroup}
  </g>`,
  });
}

