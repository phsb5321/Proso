function main() {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    throw new Error('usage: node scripts/generate-brand-vectors.mjs [--check]');
  }
  const check = args[0] === '--check';
  mkdirSync(OUT, { recursive: true });
  for (const [filename, expected] of assets()) {
    const path = resolve(OUT, filename);
    if (check) {
      let actual;
      try {
        actual = readFileSync(path, 'utf8');
      } catch {
        throw new Error(`${filename} is missing`);
      }
      if (actual !== expected) throw new Error(`${filename} is stale`);
      console.log(`checked ${filename}`);
    } else {
      writeFileSync(path, expected);
      console.log(`generated ${filename}`);
    }
  }
}

try {
  main();
} catch (error) {
  console.error(`brand vectors: FAIL — ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
